-- 공개 정보: 로그인 사용자는 조회 가능, 수정은 본인 행만.
-- profiles의 insert는 트리거가 맡으므로 정책을 두지 않는다.
create policy "profiles_select" on public.profiles
  for select to authenticated using (true);
create policy "profiles_update_own" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create policy "user_games_select" on public.user_games
  for select to authenticated using (true);
create policy "user_games_insert_own" on public.user_games
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "user_games_delete_own" on public.user_games
  for delete to authenticated using ((select auth.uid()) = user_id);

create policy "availability_select" on public.availability
  for select to authenticated using (true);
create policy "availability_insert_own" on public.availability
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "availability_update_own" on public.availability
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "availability_delete_own" on public.availability
  for delete to authenticated using ((select auth.uid()) = user_id);

-- 운영 데이터: 조회만 가능. 수정은 대시보드나 seed로 한다.
create policy "games_select" on public.games
  for select to authenticated using (true);
create policy "tag_vocabulary_select" on public.tag_vocabulary
  for select to authenticated using (true);
create policy "servers_select" on public.servers
  for select to authenticated using (true);

-- chat_members 정책에서 chat_members를 직접 조회하면 RLS가 무한 재귀에 빠진다.
-- security definer 함수로 RLS를 우회해 호출자 본인의 참여 여부만 확인한다.
create function public.is_room_member(p_room_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.chat_members
    where room_id = p_room_id
      and user_id = (select auth.uid())
  );
$$;

revoke execute on function public.is_room_member(uuid) from public, anon;
grant execute on function public.is_room_member(uuid) to authenticated;

-- 방을 만든 직후에는 아직 멤버가 아니므로 created_by도 조회를 허용해야 insert ... returning이 동작한다.
create policy "chat_rooms_select_member" on public.chat_rooms
  for select to authenticated
  using (created_by = (select auth.uid()) or public.is_room_member(id));
create policy "chat_rooms_insert_own" on public.chat_rooms
  for insert to authenticated with check (created_by = (select auth.uid()));

-- 멤버 추가는 방 생성자만 가능하다. 본인 추가를 열어 두면 아무 방에나 들어가 대화를 읽을 수 있다.
create policy "chat_members_select_member" on public.chat_members
  for select to authenticated using (public.is_room_member(room_id));
create policy "chat_members_insert_by_creator" on public.chat_members
  for insert to authenticated
  with check (
    exists (
      select 1
      from public.chat_rooms
      where id = room_id
        and created_by = (select auth.uid())
    )
  );
create policy "chat_members_delete_self" on public.chat_members
  for delete to authenticated using (user_id = (select auth.uid()));

create policy "messages_select_member" on public.messages
  for select to authenticated using (public.is_room_member(room_id));
create policy "messages_insert_member" on public.messages
  for insert to authenticated
  with check (sender_id = (select auth.uid()) and public.is_room_member(room_id));

