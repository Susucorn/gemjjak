-- 겜짝 초기 스키마: 테이블, 인덱스, 회원가입 트리거, RLS, Realtime, search_players 시그니처

-- ---------------------------------------------------------------------------
-- 테이블
-- ---------------------------------------------------------------------------

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nickname text not null,
  avatar_url text,
  bio text,
  tags text[] not null default '{}',
  onboarded boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.games (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table public.user_games (
  user_id uuid not null references public.profiles (id) on delete cascade,
  game_id bigint not null references public.games (id) on delete cascade,
  primary key (user_id, game_id)
);

-- 자정을 넘는 시간대(예: 23시~1시)는 (23, 24)와 다음 요일의 (0, 1) 두 행으로 나눠 저장한다.
create table public.availability (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  weekday smallint not null check (weekday between 1 and 7), -- ISO: 1=월, 7=일
  start_hour smallint not null check (start_hour between 0 and 23),
  end_hour smallint not null check (end_hour between 1 and 24),
  check (start_hour < end_hour),
  unique (user_id, weekday, start_hour, end_hour)
);

-- 같은 태그가 여러 게임에 있을 수 있어(예: 랭크) tag 단독으로는 키가 될 수 없다.
-- game_id가 null인 공통 태그도 중복을 막기 위해 nulls not distinct를 쓴다.
create table public.tag_vocabulary (
  id bigint generated by default as identity primary key,
  tag text not null,
  category text not null check (category in ('style', 'activity', 'want')),
  game_id bigint references public.games (id) on delete cascade,
  unique nulls not distinct (tag, category, game_id)
);

create table public.servers (
  id bigint generated by default as identity primary key,
  name text not null,
  game_id bigint references public.games (id) on delete set null,
  description text,
  invite_url text not null,
  member_count integer not null default 0 check (member_count >= 0),
  online_count integer not null default 0 check (online_count >= 0)
);

create table public.chat_rooms (
  id uuid primary key default gen_random_uuid(),
  name text, -- 1:1 방은 null
  is_group boolean not null default false,
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.chat_members (
  room_id uuid not null references public.chat_rooms (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.chat_rooms (id) on delete cascade,
  sender_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default now()
);

